import type { BethProduct, CatalogIndex, ProductKind } from './normalize.js';
import { SOURCE_LABELS, SPEC_DEFINITIONS, type SpecKey } from './spec-schema.js';

export interface ProductQualitySummary {
  totalProducts: number;
  onlineActive: number;
  recommendable: number;
  byKind: Record<string, number>;
  withSpecTable: number;
  withConflicts: number;
  conflictsByKey: Record<string, number>;
  withLegacyDisagreements: number;
  legacyDisagreementsByKey: Record<string, number>;
  missingByKey: Record<string, number>;
  coverage: Record<string, { verified: number; conflict: number; missing: number; applicable: number }>;
}

const COVERAGE_KEYS: SpecKey[] = [
  'capacityQt',
  'cookingDiameterIn',
  'cookingDimensionsIn',
  'material',
  'ovenSafeMaxF',
  'inductionCompatible',
  'coverIncluded',
  'handleStyle',
  'madeIn',
  'dishwasherRecommended',
];

const CORE_KINDS: ProductKind[] = ['cookware', 'bakeware', 'set', 'slow_cooker'];

function isOnline(p: BethProduct): boolean {
  return p.status === 'ACTIVE' && Boolean(p.url);
}

export function summarizeProductQuality(catalog: CatalogIndex): ProductQualitySummary {
  const online = catalog.products.filter(isOnline);
  const core = online.filter((p) => CORE_KINDS.includes(p.kind));
  const summary: ProductQualitySummary = {
    totalProducts: catalog.products.length,
    onlineActive: online.length,
    recommendable: online.filter((p) => p.recommendable).length,
    byKind: {},
    withSpecTable: core.filter((p) => p.quality.hasSpecTable).length,
    withConflicts: 0,
    conflictsByKey: {},
    withLegacyDisagreements: 0,
    legacyDisagreementsByKey: {},
    missingByKey: {},
    coverage: {},
  };
  for (const p of online) summary.byKind[p.kind] = (summary.byKind[p.kind] ?? 0) + 1;
  for (const p of online) {
    if (p.quality.conflicts.length) summary.withConflicts++;
    for (const c of p.quality.conflicts)
      summary.conflictsByKey[c.key] = (summary.conflictsByKey[c.key] ?? 0) + 1;
    if (p.quality.legacyDisagreements.length) summary.withLegacyDisagreements++;
    for (const d of p.quality.legacyDisagreements)
      summary.legacyDisagreementsByKey[d.key] = (summary.legacyDisagreementsByKey[d.key] ?? 0) + 1;
    for (const k of p.quality.missingExpectedSpecs)
      summary.missingByKey[k] = (summary.missingByKey[k] ?? 0) + 1;
  }
  for (const key of COVERAGE_KEYS) {
    const row = { verified: 0, conflict: 0, missing: 0, applicable: core.length };
    for (const p of core) {
      const f = p.specs[key];
      if (!f) row.missing++;
      else if (f.status === 'verified') row.verified++;
      else row.conflict++;
    }
    summary.coverage[key] = row;
  }
  return summary;
}

function pct(n: number, d: number): string {
  return d === 0 ? '—' : `${Math.round((n / d) * 100)}%`;
}

function mdEscape(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

/** Renders the product data-quality report used in docs/data-quality. */
export function renderProductQualityReport(catalog: CatalogIndex, generatedFrom: string): string {
  const s = summarizeProductQuality(catalog);
  const online = catalog.products.filter(isOnline);
  const lines: string[] = [];
  lines.push('# Product knowledge — data-quality report');
  lines.push('');
  lines.push(`Generated by \`npm run report:knowledge\` from \`${generatedFrom}\`. Do not edit by hand.`);
  lines.push('');
  lines.push('## Catalog overview');
  lines.push('');
  lines.push('| Metric | Value |');
  lines.push('|---|---|');
  lines.push(`| Products in Shopify (all statuses) | ${s.totalProducts} |`);
  lines.push(`| Active and on the Online Store | ${s.onlineActive} |`);
  lines.push(`| Recommendable now (active, online, purchasable, not a part) | ${s.recommendable} |`);
  lines.push(`| Online products with a spec conflict | ${s.withConflicts} |`);
  lines.push(
    `| Online products whose legacy tabs disagree with the live page | ${s.withLegacyDisagreements} |`,
  );
  lines.push('');
  lines.push('### Online products by kind');
  lines.push('');
  lines.push('| Kind | Products |');
  lines.push('|---|---|');
  for (const [k, v] of Object.entries(s.byKind).sort((a, b) => b[1] - a[1])) lines.push(`| ${k} | ${v} |`);
  lines.push('');
  lines.push('## Verified spec coverage (online cookware, bakeware, sets, slow cookers)');
  lines.push('');
  lines.push(
    'A spec is **verified** when a shopper-visible source states it and no other shopper-visible source contradicts it.',
  );
  lines.push('');
  lines.push('| Spec | Verified | Conflict | Not stated |');
  lines.push('|---|---|---|---|');
  for (const [key, row] of Object.entries(s.coverage)) {
    const label = SPEC_DEFINITIONS[key as SpecKey]?.label ?? key;
    lines.push(
      `| ${label} | ${row.verified} (${pct(row.verified, row.applicable)}) | ${row.conflict} | ${row.missing} |`,
    );
  }
  lines.push('');
  lines.push('## Shopper-visible conflicts (fix in Shopify before launch)');
  lines.push('');
  lines.push(
    'Beth will not state these values until the sources agree. She tells the shopper she cannot verify them.',
  );
  lines.push('');
  lines.push('| Product | Spec | Values found (source) |');
  lines.push('|---|---|---|');
  for (const p of online) {
    for (const c of p.quality.conflicts) {
      const values = c.variants
        .map((v) => `${mdEscape(v.display)} (${v.sources.map((src) => SOURCE_LABELS[src]).join('; ')})`)
        .join(' vs ');
      lines.push(`| [${mdEscape(p.title)}](${p.url}) | ${SPEC_DEFINITIONS[c.key].label} | ${values} |`);
    }
  }
  lines.push('');
  lines.push('## Stale legacy data (not shown to shoppers)');
  lines.push('');
  lines.push(
    'The `ptabs.tabs` metafield (legacy Product Tabs) is not rendered by the live theme, but it contradicts the product page on these products. Beth ignores it; cleaning it up avoids future confusion.',
  );
  lines.push('');
  lines.push('| Spec | Products affected |');
  lines.push('|---|---|');
  for (const [k, v] of Object.entries(s.legacyDisagreementsByKey)) {
    lines.push(`| ${SPEC_DEFINITIONS[k as SpecKey]?.label ?? k} | ${v} |`);
  }
  lines.push('');
  lines.push('## Missing expected specs (online, by spec)');
  lines.push('');
  lines.push('| Spec | Products missing a verified value |');
  lines.push('|---|---|');
  for (const [k, v] of Object.entries(s.missingByKey).sort((a, b) => b[1] - a[1])) {
    lines.push(`| ${SPEC_DEFINITIONS[k as SpecKey]?.label ?? k} | ${v} |`);
  }
  lines.push('');
  lines.push('## Not recommendable (active on the Online Store)');
  lines.push('');
  lines.push('| Product | Reason |');
  lines.push('|---|---|');
  for (const p of online.filter((x) => !x.recommendable)) {
    lines.push(`| [${mdEscape(p.title)}](${p.url}) | ${p.notRecommendableReasons.join('; ')} |`);
  }
  lines.push('');
  return lines.join('\n');
}
