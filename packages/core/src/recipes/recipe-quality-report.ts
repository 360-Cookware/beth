import type { CatalogIndex } from '../products/normalize.js';
import { matchMentionToProduct, type RecipeLibrary } from './recipes.js';

export interface RecipeQualitySummary {
  publishedArticles: number;
  structuredRecipes: number;
  nonRecipeArticles: number;
  withActiveProductLink: number;
  withPrepTime: number;
  withCookTime: number;
  withServings: number;
  brokenLinks: { handle: string; status: string; recipes: number }[];
  linkedProducts: { title: string; handle: string; recipes: number }[];
  unlinkedMentions: { mention: string; recipes: number; suggestedProduct: string | null }[];
}

export function summarizeRecipeQuality(library: RecipeLibrary, catalog: CatalogIndex): RecipeQualitySummary {
  const recipes = library.recipes;
  const structured = recipes.filter((r) => r.kind === 'recipe');
  const broken = new Map<string, { status: string; recipes: number }>();
  for (const r of recipes) {
    for (const l of r.productLinks) {
      if (l.status === 'active') continue;
      const e = broken.get(l.handle) ?? { status: l.status, recipes: 0 };
      e.recipes++;
      broken.set(l.handle, e);
    }
  }
  const linked = [...library.byProductId.entries()]
    .map(([id, rs]) => {
      const p = catalog.byId.get(id);
      return { title: p?.title ?? id, handle: p?.handle ?? id, recipes: rs.length };
    })
    .sort((a, b) => b.recipes - a.recipes);
  const mentions = new Map<string, number>();
  for (const r of recipes)
    for (const m of r.unlinkedEquipmentMentions) mentions.set(m, (mentions.get(m) ?? 0) + 1);

  return {
    publishedArticles: recipes.length,
    structuredRecipes: structured.length,
    nonRecipeArticles: recipes.length - structured.length,
    withActiveProductLink: structured.filter((r) => r.productLinks.some((l) => l.status === 'active')).length,
    withPrepTime: structured.filter((r) => r.prepMinutes !== null).length,
    withCookTime: structured.filter((r) => r.cookMinutes !== null).length,
    withServings: structured.filter((r) => r.servings !== null).length,
    brokenLinks: [...broken.entries()]
      .map(([handle, v]) => ({ handle, ...v }))
      .sort((a, b) => b.recipes - a.recipes),
    linkedProducts: linked,
    unlinkedMentions: [...mentions.entries()]
      .map(([mention, n]) => ({
        mention,
        recipes: n,
        suggestedProduct: matchMentionToProduct(mention, catalog)?.title ?? null,
      }))
      .sort((a, b) => b.recipes - a.recipes),
  };
}

export function renderRecipeQualityReport(
  library: RecipeLibrary,
  catalog: CatalogIndex,
  generatedFrom: string,
): string {
  const s = summarizeRecipeQuality(library, catalog);
  const pct = (n: number) => (s.structuredRecipes ? `${Math.round((n / s.structuredRecipes) * 100)}%` : '—');
  const lines: string[] = [];
  lines.push('# Recipe knowledge — data-quality report');
  lines.push('');
  lines.push(`Generated by \`npm run report:knowledge\` from \`${generatedFrom}\`. Do not edit by hand.`);
  lines.push('');
  lines.push('| Metric | Value |');
  lines.push('|---|---|');
  lines.push(`| Published articles in the Recipes blog | ${s.publishedArticles} |`);
  lines.push(`| Structured recipes (Recipe Kit ingredients/directions) | ${s.structuredRecipes} |`);
  lines.push(`| Articles without recipe data (guides, stories) | ${s.nonRecipeArticles} |`);
  lines.push(
    `| Recipes linked to at least one active product | ${s.withActiveProductLink} (${pct(s.withActiveProductLink)}) |`,
  );
  lines.push(`| Recipes with prep time | ${s.withPrepTime} (${pct(s.withPrepTime)}) |`);
  lines.push(`| Recipes with cook time | ${s.withCookTime} (${pct(s.withCookTime)}) |`);
  lines.push(`| Recipes with servings | ${s.withServings} (${pct(s.withServings)}) |`);
  lines.push('');
  lines.push('Beth shows times and servings only when the recipe states them; she never estimates them.');
  lines.push('');
  lines.push('## Products most used in recipes (active links)');
  lines.push('');
  lines.push('| Product | Recipes |');
  lines.push('|---|---|');
  for (const l of s.linkedProducts) lines.push(`| ${l.title} | ${l.recipes} |`);
  lines.push('');
  lines.push('## Broken or inactive product links in recipes');
  lines.push('');
  lines.push(
    'Beth never recommends these. Update the recipe links (or add URL redirects) to recover the product connection.',
  );
  lines.push('');
  lines.push('| Linked handle | Status | Recipes |');
  lines.push('|---|---|---|');
  for (const b of s.brokenLinks) lines.push(`| \`${b.handle}\` | ${b.status} | ${b.recipes} |`);
  lines.push('');
  lines.push('## Equipment mentioned without a link');
  lines.push('');
  lines.push('| Mention | Recipes | Possible active product (needs human confirmation) |');
  lines.push('|---|---|---|');
  for (const m of s.unlinkedMentions)
    lines.push(`| ${m.mention} | ${m.recipes} | ${m.suggestedProduct ?? '—'} |`);
  lines.push('');
  return lines.join('\n');
}
